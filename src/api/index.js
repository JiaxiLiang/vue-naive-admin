// 代码演示执行顺序
console.log('1. 同步代码开始'); // 【同步】主线程

setTimeout(() => {
  // 【宏任务】第二轮循环执行
  console.log('2. setTimeout 宏任务');
}, 0);

Promise.resolve().then(() => {
  // 【微任务】第一轮循环同步代码后立即执行
  console.log('3. Promise 微任务');
});

console.log('4. 同步代码结束'); // 【同步】主线程

// -------------------- 执行时间线 --------------------
