import axios from 'axios'
// 导入 axios HTTP 请求库
import { setupInterceptors } from './interceptors'
// 导入拦截器配置函数

export function createAxios(options = {}) {
  // 导出创建 axios 实例的工厂函数，接收可选配置参数
  const defaultOptions = { // 定义默认配置对象
    baseURL: import.meta.env.VITE_AXIOS_BASE_URL,
    // 从 Vite 环境变量中获取基础请求地址
    // import是关键字不是变量 import.meta是js自带 env是vite构建才有的后面是文件的变量
    timeout: 12000, // 设置请求超时时间为 12 秒
  }
  const service = axios.create({ // 使用 axios.create 创建一个新实例
    ...defaultOptions, // 展开合并默认配置
    ...options, // 展开合并传入的自定义配置（优先级更高）
    // 这是...是对象的展开与合并合成一个新的对象
  })
  setupInterceptors(service)
  // 调用拦截器配置函数，为该实例注入请求和响应拦截逻辑
  return service // 返回配置完成的 axios 实例
}

export const request = createAxios() // 导出默认的请求实例，用于发送业务接口请求

export const mockRequest = createAxios({ // 导出用于 Mock 数据的请求实例
  baseURL: '/mock-api', // 覆盖基础地址，指向本地 Mock 服务路径
})
