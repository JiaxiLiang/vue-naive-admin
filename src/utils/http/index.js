/*
JS 数据类型分为两类知识点

基本类型（数字、字符串等）：存在栈内存中，赋值时是复制值。
引用类型（对象、数组）：存在堆内存中，变量里存的是地址（指针）
浅拷贝
只拷贝对象的“第一层”属性。如果属性值是基本类型，就复制值；
如果属性值是引用类型（对象/数组），就复制地址。
深拷贝
递归地拷贝对象的所有层级。无论你套了多少层对象，
每一层都会被完整复制，开辟新的内存地址。
*/
